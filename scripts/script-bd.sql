/*
  MoveSync - Script do banco de dados (Azure SQL / SQL Server)
  Global Solution 2026/2 - CitizenTech

  6 tabelas:
    TB_CRUZAMENTO            cruzamentos monitorados
    TB_SEMAFORO              semáforos de cada cruzamento (FK cruzamento)
    TB_DISPOSITIVO           sensores e câmeras IoT
    TB_SEMAFORO_DISPOSITIVO  N:N semáforo x dispositivo
    TB_LEITURA_TRAFEGO       leituras enviadas pelos dispositivos (FK semáforo + dispositivo)
    TB_AJUSTE_TEMPO          histórico dos ajustes automáticos do tempo de verde (FK semáforo)

  Os dados de IoT são FICTÍCIOS (simulados) - não há hardware real.
  O Hibernate (spring.jpa.hibernate.ddl-auto=update) também cria/atualiza as tabelas ao subir a aplicação;
  este script é a referência oficial do DDL e é executado pelo /scripts/infra-azure.sh.
*/

/* ===================== DROPS (ordem inversa das FKs) ===================== */
DROP TABLE IF EXISTS TB_AJUSTE_TEMPO;
DROP TABLE IF EXISTS TB_LEITURA_TRAFEGO;
DROP TABLE IF EXISTS TB_SEMAFORO_DISPOSITIVO;
DROP TABLE IF EXISTS TB_DISPOSITIVO;
DROP TABLE IF EXISTS TB_SEMAFORO;
DROP TABLE IF EXISTS TB_CRUZAMENTO;

/* ================================ DDL ================================ */
CREATE TABLE TB_CRUZAMENTO (
    ID_CRUZAMENTO BIGINT IDENTITY(1,1) PRIMARY KEY,
    NOME          VARCHAR(100) NOT NULL,
    ENDERECO      VARCHAR(255) NOT NULL,
    BAIRRO        VARCHAR(255),
    LATITUDE      FLOAT,
    LONGITUDE     FLOAT,
    CONSTRAINT ck_cruzamento_lat CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT ck_cruzamento_lng CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE TABLE TB_SEMAFORO (
    ID_SEMAFORO    BIGINT IDENTITY(1,1) PRIMARY KEY,
    CODIGO         VARCHAR(20) NOT NULL,
    TIPO           VARCHAR(20) NOT NULL,
    STATUS         VARCHAR(20) NOT NULL DEFAULT 'ATIVO',
    TEMPO_VERDE    INT NOT NULL,
    TEMPO_AMARELO  INT NOT NULL,
    TEMPO_VERMELHO INT NOT NULL,
    ID_CRUZAMENTO  BIGINT NOT NULL,
    CONSTRAINT uq_semaforo_codigo UNIQUE (CODIGO),
    CONSTRAINT ck_semaforo_tipo   CHECK (TIPO IN ('VEICULAR', 'PEDESTRE')),
    CONSTRAINT ck_semaforo_status CHECK (STATUS IN ('ATIVO', 'INATIVO', 'MANUTENCAO')),
    CONSTRAINT ck_semaforo_tempos CHECK (TEMPO_VERDE > 0 AND TEMPO_AMARELO > 0 AND TEMPO_VERMELHO > 0),
    CONSTRAINT fk_semaforo_cruzamento FOREIGN KEY (ID_CRUZAMENTO) REFERENCES TB_CRUZAMENTO (ID_CRUZAMENTO)
);

CREATE TABLE TB_DISPOSITIVO (
    ID_DISPOSITIVO BIGINT IDENTITY(1,1) PRIMARY KEY,
    CODIGO         VARCHAR(20) NOT NULL,
    TIPO           VARCHAR(20) NOT NULL,
    MODELO         VARCHAR(60),
    FL_ONLINE      BIT NOT NULL DEFAULT 1,
    CONSTRAINT uq_dispositivo_codigo UNIQUE (CODIGO),
    CONSTRAINT ck_dispositivo_tipo CHECK (TIPO IN ('CAMERA', 'SENSOR_INDUTIVO', 'SENSOR_PRESENCA'))
);

CREATE TABLE TB_SEMAFORO_DISPOSITIVO (
    ID_SEMAFORO    BIGINT NOT NULL,
    ID_DISPOSITIVO BIGINT NOT NULL,
    CONSTRAINT pk_semaforo_dispositivo PRIMARY KEY (ID_SEMAFORO, ID_DISPOSITIVO),
    CONSTRAINT fk_semdisp_semaforo    FOREIGN KEY (ID_SEMAFORO)    REFERENCES TB_SEMAFORO (ID_SEMAFORO),
    CONSTRAINT fk_semdisp_dispositivo FOREIGN KEY (ID_DISPOSITIVO) REFERENCES TB_DISPOSITIVO (ID_DISPOSITIVO)
);

CREATE TABLE TB_LEITURA_TRAFEGO (
    ID_LEITURA       BIGINT IDENTITY(1,1) PRIMARY KEY,
    ID_SEMAFORO      BIGINT NOT NULL,
    ID_DISPOSITIVO   BIGINT NOT NULL,
    DT_HORA_LEITURA  DATETIME2 NOT NULL,
    QTD_VEICULOS     INT NOT NULL,
    QTD_PEDESTRES    INT NOT NULL,
    VELOCIDADE_MEDIA FLOAT,
    CONSTRAINT ck_leitura_qtds CHECK (QTD_VEICULOS >= 0 AND QTD_PEDESTRES >= 0),
    CONSTRAINT fk_leitura_semaforo    FOREIGN KEY (ID_SEMAFORO)    REFERENCES TB_SEMAFORO (ID_SEMAFORO),
    CONSTRAINT fk_leitura_dispositivo FOREIGN KEY (ID_DISPOSITIVO) REFERENCES TB_DISPOSITIVO (ID_DISPOSITIVO)
);

CREATE TABLE TB_AJUSTE_TEMPO (
    ID_AJUSTE            BIGINT IDENTITY(1,1) PRIMARY KEY,
    ID_SEMAFORO          BIGINT NOT NULL,
    DT_HORA_AJUSTE       DATETIME2 NOT NULL,
    TEMPO_VERDE_ANTERIOR INT NOT NULL,
    TEMPO_VERDE_NOVO     INT NOT NULL,
    MEDIA_VEICULOS       FLOAT NOT NULL,
    MOTIVO               VARCHAR(255),
    CONSTRAINT fk_ajuste_semaforo FOREIGN KEY (ID_SEMAFORO) REFERENCES TB_SEMAFORO (ID_SEMAFORO)
);

CREATE INDEX ix_leitura_semaforo_data ON TB_LEITURA_TRAFEGO (ID_SEMAFORO, DT_HORA_LEITURA DESC);

